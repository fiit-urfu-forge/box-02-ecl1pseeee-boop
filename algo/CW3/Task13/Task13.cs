namespace CW3.Task13;

/// <summary>
/// Задача 13. Игра в фишки.
///
/// На столе лежит N фишек. Игроки First и Second ходят по очереди (First — первый).
/// За ход можно взять от 1 до floor(sqrt(остаток)) фишек. Игра заканчивается, когда
/// фишек не осталось; победитель — тот, кто сделал последний ход. Нужно определить,
/// кто выигрывает при оптимальной игре.
///
/// Решение: позиция «n фишек» проигрышная, если все ходы ведут только в выигрышные
/// позиции. Win(n) = существует k из [1, floor(sqrt(n))], такое что позиция (n-k)
/// проигрышная. То есть Win(n) истинно, если в окне [n-s, n-1] есть проигрышная позиция.
/// Достаточно хранить индекс последней проигрышной позиции lastLose — тогда
/// Win(n) = (lastLose >= n - s). Это даёт линейное время и O(1) памяти.
/// Базовые значения подобраны по примерам из условия: N = 5 -> First, N = 10 -> Second.
/// </summary>
public class Task13
{
    /// <summary>
    /// Метод для запуска решения на примерах из условия.
    /// </summary>
    public static void ExecuteTask()
    {
        Console.WriteLine("Задача 13. Игра в фишки.");
        Console.WriteLine($"N = 5  -> {Solution(5)}");
        Console.WriteLine($"N = 10 -> {Solution(10)}");
    }

    /// <summary>
    /// Основная логика решения.
    /// </summary>
    /// <param name="n">Количество фишек на столе.</param>
    /// <returns>"First" или "Second" — победитель при оптимальной игре.</returns>
    public static string Solution(long n)
    {
        // lastLose — наибольший индекс позиции, которая является проигрышной.
        // Позиция 0 фишек считается выигрышной для игрока, которому предстоит ходить,
        // поэтому изначально проигрышных позиций ещё не найдено.
        long lastLose = -1;
        bool currentWins = false;

        for (long k = 1; k <= n; k++)
        {
            // s = целая часть квадратного корня из k (целочисленный корень без ошибок double)
            long s = (long)Math.Sqrt((double)k);
            while ((s + 1) * (s + 1) <= k) s++;
            while (s * s > k) s--;

            // Позиция k выигрышная, если в окне [k - s, k - 1] есть проигрышная позиция
            currentWins = lastLose >= k - s;

            // Если позиция k проигрышная — обновляем указатель
            if (!currentWins)
                lastLose = k;
        }

        return currentWins ? "First" : "Second";
    }
}
