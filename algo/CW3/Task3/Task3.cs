namespace CW3.Task3;

/// <summary>
/// Задача 3. Танец точек.
///
/// На прямой стоят N точек. Каждой точке разрешается сделать ровно одно движение
/// в любую сторону на расстояние не больше L. Точки, оказавшиеся после танца в одной
/// позиции, сливаются в одну. Нужно найти минимальное количество точек, которое
/// может остаться на прямой.
///
/// Идея: точка с координатой Vi после движения может занять любую позицию из отрезка
/// [Vi - L, Vi + L]. Две точки можно слить, если их отрезки пересекаются. Значит задача
/// сводится к классической задаче «минимальное число точек, протыкающих все отрезки».
/// Так как все отрезки имеют одинаковую ширину 2L, жадность сводится к простому проходу
/// по отсортированным координатам.
/// </summary>
public class Task3
{
    /// <summary>
    /// Метод для запуска решения на примере из условия.
    /// </summary>
    public static void ExecuteTask()
    {
        long l = 10;
        long[] v = { 30, 3, 14, 19, 21 };

        Console.WriteLine("Задача 3. Танец точек.");
        Console.WriteLine($"L = {l}, точки = [{string.Join(", ", v)}]");
        Console.WriteLine($"Результат: {Solution(l, v)}");
    }

    /// <summary>
    /// Основная логика решения.
    /// </summary>
    /// <param name="l">Максимальное расстояние одного движения точки.</param>
    /// <param name="points">Координаты точек.</param>
    /// <returns>Минимальное количество точек после окончания танца.</returns>
    public static int Solution(long l, long[] points)
    {
        if (points == null || points.Length == 0)
            return 0;

        // Сортируем координаты, чтобы идти по прямой слева направо
        long[] sorted = (long[])points.Clone();
        Array.Sort(sorted);

        int groups = 0;
        int i = 0;
        int n = sorted.Length;

        while (i < n)
        {
            // Начинаем новую группу с самой левой ещё не покрытой точки.
            // «Точку слияния» ставим как можно правее — в позицию sorted[i] + L.
            // Тогда в эту группу попадут все точки, чьи отрезки [Vj - L, Vj + L]
            // накрывают эту позицию, то есть sorted[j] <= sorted[i] + 2L.
            long groupRightLimit = sorted[i] + 2 * l;
            groups++;

            while (i < n && sorted[i] <= groupRightLimit)
                i++;
        }

        return groups;
    }
}
