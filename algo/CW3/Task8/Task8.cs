namespace CW3.Task8;

/// <summary>
/// Задача 8. Интересная игра с числами.
///
/// Дана таблица 2×N. Игроки по очереди (первый ходит первым) выбирают ещё не выбранный
/// столбец j: первый игрок прибавляет к своим очкам Aj, второй — Bj. После игры
/// считается стоимость S1 - S2. Первый максимизирует S1 - S2, второй — S2 - S1.
/// Нужно найти стоимость игры при оптимальной игре обоих.
///
/// Решение: вклад столбца j в величину (S1 - S2) равен +Aj, если его забрал первый,
/// и -Bj, если его забрал второй. «Важность» столбца — это разница этих вариантов,
/// то есть Aj + Bj. Поэтому оба игрока в свой ход забирают столбец с наибольшим Aj + Bj.
/// Сортируем столбцы по убыванию Aj + Bj: чётные позиции достаются первому, нечётные — второму.
/// </summary>
public class Task8
{
    /// <summary>
    /// Метод для запуска решения на примерах из условия.
    /// </summary>
    public static void ExecuteTask()
    {
        Console.WriteLine("################ Задача 8. Интересная игра с числами ################\n");

        int[][] example1 = { new[] { 1, 1 } };
        int[][] example2 = { new[] { 1, 1 }, new[] { 1, 1 } };
        int[][] example3 = { new[] { 1, 2 }, new[] { 3, 4 }, new[] { 5, 6 } };

        Console.WriteLine($"Пример 1 -> {Solution(example1)} (ожидается 1)");
        Console.WriteLine($"Пример 2 -> {Solution(example2)} (ожидается 0)");
        Console.WriteLine($"Пример 3 -> {Solution(example3)} (ожидается 2)");
        Console.WriteLine("════════════════════════════════════════\n");
    }

    /// <summary>
    /// Основная логика решения.
    /// </summary>
    /// <param name="columns">Массив столбцов, каждый столбец — пара (Ai, Bi).</param>
    /// <returns>Стоимость игры S1 - S2 при оптимальной игре обоих игроков.</returns>
    public static long Solution(int[][] columns)
    {
        // Копируем и сортируем столбцы по убыванию суммы Ai + Bi
        int[][] sorted = (int[][])columns.Clone();
        Array.Sort(sorted, (x, y) => (y[0] + y[1]).CompareTo(x[0] + x[1]));

        long cost = 0;
        for (int i = 0; i < sorted.Length; i++)
        {
            // Чётные позиции (0, 2, 4, ...) забирает первый игрок,
            // нечётные (1, 3, 5, ...) — второй игрок
            if (i % 2 == 0)
                cost += sorted[i][0];   // +Ai первому игроку
            else
                cost -= sorted[i][1];   // -Bi (очки уходят второму игроку)
        }

        return cost;
    }
}
